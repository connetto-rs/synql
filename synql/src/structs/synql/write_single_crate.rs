//! Submodule implementing the writing of a workspace as a single crate.

use std::{
    io::Write,
    path::{Path, PathBuf},
};

use quote::{format_ident, quote};

use super::write_rust_file;
use crate::{
    structs::{DescribedCrate, SynQL, TomlDependency, Workspace},
    traits::{SynQLDatabaseLike, UserDefinedTypeSynLike, table::TableSynLike},
};

impl<DB: SynQLDatabaseLike> SynQL<'_, DB> {
    /// Returns the path of the single crate holding the workspace, relative
    /// to the workspace.
    pub(super) fn single_crate_relative_path(workspace: &Workspace) -> PathBuf {
        workspace.crate_base_path().join(workspace.name())
    }

    /// Writes the workspace as a single crate named after it, and returns
    /// the names of the workspace dependencies it declares.
    ///
    /// The models and their dependencies sit behind the default `models`
    /// feature, and the SQLite conversions of the enum types, of the column
    /// types and of the base crates behind the default `sqlite` feature.
    pub(super) fn write_single_crate(
        &self,
        workspace: &Workspace,
    ) -> Result<Vec<String>, crate::Error> {
        let name = workspace.name();
        let crate_path = workspace.path().join(Self::single_crate_relative_path(workspace));
        let src_path = crate_path.join("src");
        std::fs::create_dir_all(&src_path)?;
        let tables = self.generated_tables()?;
        let enum_types: Vec<&DB::UserDefinedType> = self.enum_types(workspace).collect();

        let mut workspace_dependencies = if tables.is_empty() {
            Vec::new()
        } else {
            self.table_crate_dependencies(&tables, name, workspace)?
        };
        if !enum_types.is_empty() {
            for enum_dependency in ["serde", "diesel"] {
                if !workspace_dependencies.iter().any(|declared| declared == enum_dependency) {
                    workspace_dependencies.push(enum_dependency.to_owned());
                }
            }
        }
        let mut dependencies = Vec::new();
        for dependency_name in &workspace_dependencies {
            let mut dependency = TomlDependency::new(dependency_name).workspace(true)?;
            if dependency_name == "diesel" && !enum_types.is_empty() {
                dependency = dependency.feature("postgres_backend");
            }
            dependencies.push(dependency.optional(true));
        }
        dependencies.extend(
            self.callback_dependencies(&tables, &workspace_dependencies)?
                .into_iter()
                .map(|dependency| dependency.optional(true)),
        );
        for callback in &self.sink_toml_callbacks {
            if let Some(dependency) = callback(self.database)?
                && !dependencies.iter().any(|declared| declared.name() == dependency.name())
            {
                dependencies.push(dependency.optional(true));
            }
        }

        let base_type_crates = self.base_type_crates(workspace)?;
        let mut models_feature = Vec::new();
        let mut sqlite_feature = vec!["models".to_owned()];
        if !enum_types.is_empty() {
            sqlite_feature.push("diesel/sqlite".to_owned());
        }
        for dependency in &dependencies {
            let dependency_name = dependency.name();
            models_feature.push(format!("dep:{dependency_name}"));
            let single_base_crate = workspace.is_single_base_crate(dependency_name);
            if single_base_crate {
                models_feature.push(format!("{dependency_name}/models"));
            }
            if single_base_crate
                || base_type_crates.iter().any(|type_crate| type_crate.name() == dependency_name)
                || workspace.external_crates().any(|external_crate| {
                    external_crate.name() == dependency_name
                        && self.forwards_sqlite(workspace, external_crate)
                })
            {
                sqlite_feature.push(format!("{dependency_name}/sqlite"));
            }
        }

        let mut buffer = std::fs::File::create(crate_path.join("Cargo.toml"))?;
        let description = if self.sql.is_some() {
            format!("Diesel models and description of the {name} workspace, generated by synql.")
        } else {
            format!("Diesel models of the {name} workspace, generated by synql.")
        };
        write!(buffer, "{}", workspace.package_section(name, &description))?;
        writeln!(buffer, "\n[dependencies]")?;
        for dependency in &dependencies {
            writeln!(buffer, "{dependency}")?;
        }
        writeln!(buffer, "\n[features]")?;
        writeln!(buffer, "default = {}", toml_list(&["models", "sqlite"]))?;
        writeln!(buffer, "models = {}", toml_list(&models_feature))?;
        writeln!(buffer, "sqlite = {}", toml_list(&sqlite_feature))?;
        writeln!(buffer, "\n[lints]")?;
        writeln!(buffer, "workspace = true")?;

        if let Some(sql) = &self.sql {
            let described_crate = DescribedCrate::new(
                name.to_owned(),
                tables.iter().copied().map(TableSynLike::table_snake_name).collect(),
                enum_types.iter().copied().map(UserDefinedTypeSynLike::qualified_name).collect(),
            );
            self.write_description(sql, vec![described_crate], workspace, &crate_path)?;
        }
        self.write_single_crate_lib(&tables, &enum_types, workspace, &src_path.join("lib.rs"))?;

        Ok(dependencies
            .iter()
            .filter(|dependency| dependency.is_workspace())
            .map(|dependency| dependency.name().to_owned())
            .collect())
    }

    /// Writes the `lib.rs` of the single crate holding `tables` and
    /// `enum_types` at `lib_rs_path`.
    fn write_single_crate_lib(
        &self,
        tables: &[&DB::Table],
        enum_types: &[&DB::UserDefinedType],
        workspace: &Workspace,
        lib_rs_path: &Path,
    ) -> Result<(), crate::Error> {
        let models = quote! { #[cfg(feature = "models")] };
        let crate_ident = format_ident!("{}", workspace.name().replace('-', "_"));
        let allow_non_snake_case = tables
            .iter()
            .any(|table| !table.has_snake_case_table_name())
            .then(|| quote! { #![allow(non_snake_case)] });
        let allow_ambiguous_glob_reexports = (tables.len() > 1).then(|| {
            quote! {
                #![allow(ambiguous_glob_reexports, reason = "TableModel trait names can collide across tables")]
            }
        });
        let description_constant = self.sql.as_ref().map(|_| Self::description_constant());

        let enum_modules = enum_types.iter().map(|enum_type| {
            let module_ident = enum_type.enum_module_ident();
            let items = Self::enum_items(enum_type);
            quote! {
                #models
                pub mod #module_ident {
                    #items
                }
            }
        });
        let mut table_modules = Vec::with_capacity(tables.len());
        for table in tables {
            let items = self.table_items(table, workspace)?;
            table_modules.push(Self::table_module(table, &items, &models));
        }
        let mut sink_items = Vec::new();
        for callback in &self.sink_callbacks {
            if let Some(items) = callback(tables, self.database, workspace)? {
                let file = syn::parse2::<syn::File>(items).map_err(|source| {
                    crate::Error::UnparsableCode { path: lib_rs_path.to_path_buf(), source }
                })?;
                let attributes = file.attrs;
                let items = file.items.iter().map(|item| quote! { #models #item });
                sink_items.push(quote! {
                    #(#attributes)*
                    #(#items)*
                });
            }
        }

        let content = quote! {
            #allow_non_snake_case
            #allow_ambiguous_glob_reexports
            extern crate self as #crate_ident;
            #description_constant
            #(#enum_modules)*
            #(#table_modules)*
            #(#sink_items)*
        };
        write_rust_file(lib_rs_path, content)
    }
}

/// Returns `entries` as a TOML array of strings.
fn toml_list<S: AsRef<str>>(entries: &[S]) -> String {
    let entries: Vec<String> =
        entries.iter().map(|entry| crate::structs::toml_string(entry.as_ref())).collect();
    format!("[{}]", entries.join(", "))
}
